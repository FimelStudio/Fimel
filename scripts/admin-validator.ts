import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { librarySchema } from '../admin/shared/schema';

// Compile only during the build. Browser and Worker execute static validation code.
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
addFormats(ajv);
const validator = ajv.compile(librarySchema);
const bundled = await build({
  stdin: { contents: standaloneCode(ajv, validator), resolveDir: resolve('.'), loader: 'js' },
  bundle: true, format: 'esm', platform: 'browser', target: 'es2023', write: false,
});
await writeFile('admin/shared/generated/library-validator.js', '// Generated by npm run admin:generate. Edit schema.ts instead.\n' + bundled.outputFiles[0].text);
console.log('Generated static library validator; runtime compilation is unnecessary.');
